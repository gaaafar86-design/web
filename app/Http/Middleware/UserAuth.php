<?php

namespace App\Http\Middleware;

use Closure;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Symfony\Component\HttpFoundation\Response;

class UserAuth
{
    /**
     * التحقق من تسجيل الدخول وحالة حساب المستخدم.
     */
    public function handle(
        Request $request,
        Closure $next
    ): Response {
        $guard = Auth::guard('web');

        /*
        |--------------------------------------------------------------------------
        | التحقق من تسجيل الدخول
        |--------------------------------------------------------------------------
        */
        if (!$guard->check()) {
            return redirect()
                ->route('user.login')
                ->with(
                    'error',
                    'يرجى تسجيل الدخول أولاً.'
                );
        }

        /*
        |--------------------------------------------------------------------------
        | جلب آخر بيانات المستخدم من قاعدة البيانات
        |--------------------------------------------------------------------------
        */
        $user = $guard->user()->fresh();

        if (!$user) {
            $guard->logout();

            $request->session()->invalidate();
            $request->session()->regenerateToken();

            return redirect()
                ->route('user.login')
                ->with(
                    'error',
                    'لم يتم العثور على حساب المستخدم.'
                );
        }

        /*
        |--------------------------------------------------------------------------
        | قراءة القيمة الأصلية للحالة
        |--------------------------------------------------------------------------
        | نستخدم getRawOriginal حتى لا يتأثر الفحص بأي Accessor
        | يحوّل 1 إلى Active أو 0 إلى Inactive.
        |--------------------------------------------------------------------------
        */
        $rawStatus = $user->getRawOriginal('status');

        /*
        |--------------------------------------------------------------------------
        | الحساب المفعّل
        |--------------------------------------------------------------------------
        | القيمة الصحيحة للحساب المفعّل هي 1.
        |--------------------------------------------------------------------------
        */
        $isActive = (string) $rawStatus === '1';

        /*
        |--------------------------------------------------------------------------
        | تسجيل خروج المستخدم إذا كان غير مفعّل
        |--------------------------------------------------------------------------
        */
        if (!$isActive) {
            $guard->logout();

            $request->session()->invalidate();
            $request->session()->regenerateToken();

            return redirect()
                ->route('user.login')
                ->with(
                    'error',
                    'تم تعطيل حسابك من قبل الإدارة. يرجى التواصل مع المكتب.'
                );
        }

        return $next($request);
    }
}
